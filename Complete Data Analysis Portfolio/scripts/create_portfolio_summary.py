"""Create an executed cross-project summary notebook from validated outputs."""

from __future__ import annotations

import contextlib
import io
import json
from pathlib import Path
import sys

import nbformat

ROOT=Path(__file__).resolve().parents[1]
DOMAINS=("sales","healthcare","sports","finance","ecommerce")
CODE="""from pathlib import Path
import json
import pandas as pd

def find_project_root(start=Path.cwd()):
    for candidate in (start.resolve(), *start.resolve().parents):
        if (candidate / 'PRD.md').is_file() and (candidate / 'src').is_dir():
            return candidate
    raise FileNotFoundError('Run inside the portfolio project.')

PROJECT_ROOT=find_project_root()
domains=['sales','healthcare','sports','finance','ecommerce']
headline_keys={
 'sales':'gross_line_sales_gbp',
 'healthcare':'readmission_within_30d_rate',
 'sports':'elo_holdout_accuracy',
 'finance':'equal_weight_annualized_price_return',
 'ecommerce':'session_conversion_rate',
}
rows=[]
for domain in domains:
    doc=json.loads((PROJECT_ROOT/'outputs'/domain/'metrics.json').read_text(encoding='utf-8'))
    metric=next(m for m in doc['metrics'] if m['metric_id']==headline_keys[domain])
    manifest=pd.read_csv(PROJECT_ROOT/'visualizations'/domain/'manifest.csv')
    rows.append({'domain':domain,'coverage':'; '.join(str(v) for v in doc['coverage'].values() if v),
                 'headline_metric':metric['metric_id'],'value':metric['value'],'unit':metric['unit'],
                 'charts':len(manifest),'limitations':len(doc['limitations'])})
summary=pd.DataFrame(rows)
print(summary.to_string(index=False))
print('Portfolio chart count:',int(summary['charts'].sum()))
print('Domain outputs are separate; do not compare unlike currencies, units, or denominators.')
"""


def main()->None:
    os_cwd=Path.cwd();
    import os
    os.chdir(ROOT)
    nb=nbformat.v4.new_notebook()
    nb.metadata.update({"kernelspec":{"display_name":"Python (Complete Data Analysis Portfolio)","language":"python","name":"portfolio"},"language_info":{"name":"python"}})
    nb.metadata["portfolio_summary"]=True
    nb.cells=[
        nbformat.v4.new_markdown_cell("# Portfolio summary\n\nThis notebook provides navigation and a compact index of the five completed domain analyses. Metrics remain domain-specific and are not combined across incompatible units."),
        nbformat.v4.new_markdown_cell("## Coverage and key evidence\n\nThe table below reads the versioned metrics and chart manifests generated by each domain builder. Detailed methods, recommendations, source limits, and figures are linked from each project README."),
        nbformat.v4.new_code_cell(CODE),
        nbformat.v4.new_markdown_cell("## Project navigation\n\n- [Sales analysis](project1_sales_analysis/README.md)\n- [Healthcare analysis](project2_healthcare_analysis/README.md)\n- [Sports analytics](project3_sports_analytics/README.md)\n- [Financial analysis](project4_financial_analysis/README.md)\n- [E-commerce analysis](project5_ecommerce_analytics/README.md)\n\nThe portfolio is an educational analysis of historical datasets; it is not clinical, investment, or causal advice."),
    ]
    output=io.StringIO();namespace={"__name__":"__main__"}
    with contextlib.redirect_stdout(output):exec(compile(CODE,"portfolio_summary_cell","exec"),namespace)
    nb.cells[2].execution_count=1;nb.cells[2].outputs=[nbformat.v4.new_output("stream",name="stdout",text=output.getvalue())]
    target=ROOT/"portfolio_summary.ipynb";nbformat.write(nb,target)
    os.chdir(os_cwd)
    print(f"WROTE {target.relative_to(ROOT)}")


if __name__=="__main__":main()
